import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { scanText, auditRepository, parseLocalEnvSecrets } from './audit-secrets.mjs';

const random = () => randomBytes(32).toString('hex');
const generated = 'ghp_' + random();
const rawDollars = '$2a$10$' + random();
assert.equal(parseLocalEnvSecrets(`export CURSEFORGE_API_KEY="${rawDollars}" # comment`)[0].value, rawDollars);
assert.equal(parseLocalEnvSecrets(`CRON_SECRET='${rawDollars}'`)[0].value, rawDollars);
assert.equal(parseLocalEnvSecrets(`CRON_SECRET=${rawDollars} # comment`)[0].value, rawDollars);
assert.equal(parseLocalEnvSecrets('VITE_MS_CLIENT_ID=public-id\nSUPABASE_ANON_KEY=public-key').length, 0);
assert.equal(parseLocalEnvSecrets('CRON_SECRET="${UNEXPANDED}"')[0].value, '${UNEXPANDED}');
const findings = scanText(`const key = "${generated}";\n`, 'fixture.ts');
assert.equal(findings[0]?.type, 'github-token');
assert.equal(findings[0]?.line, 1);
assert.ok(!JSON.stringify(findings).includes(generated));
assert.ok(!JSON.stringify(findings).includes('const key'));
assert.equal(scanText('CURSEFORGE_API_KEY=your_api_key_here').length, 0);
assert.equal(scanText('CRON_SECRET=replace_me_with_a_secret').length, 0);
assert.equal(scanText('TP_MASTER_SECRET=process.env.TP_MASTER_SECRET').length, 0);
assert.equal(scanText(`CRON_SECRET="${random()}"`)[0]?.severity, 'high');
assert.equal(scanText(JSON.stringify({ CRON_SECRET: random() }))[0]?.severity, 'high');
assert.equal(scanText(JSON.stringify({ master: random() }), 'deploy-secrets.json').filter(x => x.type === 'private-json-store').length, 1);
assert.equal(scanText(`CURSEFORGE_API_KEY: &str = r#"${'$2a$10$'}${random()}"#;`)[0]?.type, 'bcrypt-or-curseforge-key');
const encode = object => Buffer.from(JSON.stringify(object)).toString('base64url');
const anon = `${encode({ alg: 'HS256', typ: 'JWT' })}.${encode({ role: 'anon', iss: 'supabase', sub: random() })}.${random()}`;
assert.equal(scanText(anon)[0]?.severity, 'info');
const service = `${encode({ alg: 'HS256', typ: 'JWT' })}.${encode({ role: 'service_role', iss: 'supabase', sub: random() })}.${random()}`;
assert.equal(scanText(service)[0]?.severity, 'high');
const publicClient = '00000000-0000-4000-8000-000000000001';
assert.equal(scanText(`DEFAULT_CLIENT_ID: &str = "${publicClient}"`)[0]?.type, 'oauth-public-client-id');
assert.ok(!JSON.stringify(scanText(`CRON_SECRET="${generated}"`)).includes(generated));
assert.equal(scanText(`DATABASE_URL="postgres://owner:${random()}@db.invalid/db"`).filter(item => item.type === 'database-url-with-password').length, 1);
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'tp-secret-audit-test-'));
try {
  const git = args => execFileSync('git', args, { cwd: temporary, windowsHide: true, stdio: 'pipe' });
  git(['init', '-q']);
  const target = path.join(temporary, 'fixture.txt');
  fs.writeFileSync(target, generated);
  git(['add', '--', 'fixture.txt']);
  fs.writeFileSync(target, 'No credential in the working copy.');
  assert.equal(auditRepository({ cwd: temporary }).summary.high, 0);
  const staged = auditRepository({ cwd: temporary, staged: true });
  assert.equal(staged.summary.high, 1);
  assert.equal(staged.findings[0].scope, 'staged');
  assert.ok(!JSON.stringify(staged).includes(generated));
  const exactValue = random();
  fs.writeFileSync(path.join(temporary, '.gitignore'), '.env\n');
  fs.writeFileSync(path.join(temporary, '.env'), `CRON_SECRET='${exactValue}'\n`);
  fs.writeFileSync(target, exactValue);
  git(['add', '--', 'fixture.txt']);
  fs.writeFileSync(target, 'No credential in the working copy.');
  const exactStaged = auditRepository({ cwd: temporary, staged: true, localSecretFiles: ['.env'] });
  assert.equal(exactStaged.exactSecretScan.matches, 1);
  assert.equal(exactStaged.findings.find(item => item.type === 'exact-local-secret-match')?.secretName, 'CRON_SECRET');
  assert.ok(!JSON.stringify(exactStaged).includes(exactValue));
  const binaryPath = path.join(temporary, 'payload.exe');
  fs.writeFileSync(binaryPath, Buffer.concat([Buffer.from('MZ'), Buffer.from(exactValue, 'utf8'), Buffer.from([0]), Buffer.from(exactValue, 'utf16le')]));
  const exact = auditRepository({ cwd: temporary, binaries: ['payload.exe'], localSecretFiles: ['.env'] });
  const binaryMatch = exact.findings.find(item => item.scope === 'binary' && item.type === 'exact-local-secret-match');
  assert.equal(binaryMatch?.secretName, 'CRON_SECRET');
  assert.equal(binaryMatch?.found, true);
  assert.deepEqual(binaryMatch?.encodings, ['utf8', 'utf16le']);
  assert.ok(!JSON.stringify(exact).includes(exactValue));
  fs.writeFileSync(binaryPath, exactValue.slice(0, -1));
  const partial = auditRepository({ cwd: temporary, binaries: ['payload.exe'], localSecretFiles: ['.env'] });
  assert.equal(partial.exactSecretScan.matches, 0);
} finally {
  const actual = fs.realpathSync(temporary);
  const parent = fs.realpathSync(os.tmpdir());
  assert.equal(path.dirname(actual), parent);
  assert.ok(path.basename(actual).startsWith('tp-secret-audit-test-'));
  fs.rmSync(actual, { recursive: true, force: true });
}
console.log('Secret audit: redaction, exact ENV UTF8/UTF16 matching, dollar preservation, key types and staged/worktree isolation passed.');

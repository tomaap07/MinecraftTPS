import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync(new URL('../src/lib/console_buffer.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {boundedConsole,consoleCanExpire,CONSOLE_IDLE_MS,CONSOLE_LINE_LIMIT} = await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const logs = Array.from({length:12000},(_,i)=>({id:i,stream:i===11999?'stderr':'stdout'}));
const visible = boundedConsole(logs);
assert.equal(visible.length,1500);
assert.equal(visible[0].id,10500);
assert.equal(visible.at(-1).id,11999,'The latest crash line must remain visible');
assert.equal(logs.length,12000,'Archival data must not be mutated');
assert.equal(CONSOLE_LINE_LIMIT,1500);
assert.equal(consoleCanExpire(CONSOLE_IDLE_MS-1,0,false),false);
assert.equal(consoleCanExpire(CONSOLE_IDLE_MS,0,false),true);
assert.equal(consoleCanExpire(CONSOLE_IDLE_MS*2,0,true),false,'An active game must prevent cleanup');
assert.equal(consoleCanExpire(CONSOLE_IDLE_MS*2,CONSOLE_IDLE_MS+1,false),false,'Interaction/log arrival must renew the timeout');
assert.equal(consoleCanExpire(10,20,false),false,'Clock corrections must not expire the buffer');
console.log('Console buffer: 1500 lines, latest errors preserved, 12-minute idle with active-game and interaction guards.');

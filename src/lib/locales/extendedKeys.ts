export function extendedCatalog(code: string, lines: string): Record<string,string> {
  const values=lines.trim().split(/\r?\n/).map(line=>line.trim());
  if(values.length!==extendedKeys.length) throw new Error(`Locale ${code}: ${values.length} entries, expected ${extendedKeys.length}`);
  return Object.fromEntries(extendedKeys.map((key,index)=>[key,values[index]]));
}
